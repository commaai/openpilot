// opendbc-gen.js against opendbc's own generator.py: every generated DBC of a local opendbc checkout, byte for byte.
// usage: node opendbc-gen.mjs [opendbc repo dir]
import fs from "node:fs";
import path from "node:path";
import {execFileSync} from "node:child_process";
import {Generator} from "../opendbc-gen.js";

const PYTHON = process.env.PYTHON || "/home/batman/openpilot/.venv/bin/python";
const repo = process.argv[2] || "/home/batman/openpilot/opendbc_repo";
const gen = path.join(repo, "opendbc/dbc/generator");

const files = fs.readdirSync(gen, {recursive: true}).filter((f) => !f.includes("__pycache__") && fs.statSync(path.join(gen, f)).isFile());
const g = new Generator(files, async (f) => fs.existsSync(path.join(gen, f)) ? fs.readFileSync(path.join(gen, f), "utf8") : null);

const ref = JSON.parse(execFileSync(PYTHON, ["-c", "import json, sys; sys.path.insert(0, sys.argv[1]); from opendbc.dbc.generator.generator import generate_all; print(json.dumps(generate_all()))", repo], {maxBuffer: 1 << 28}).toString());

let bad = 0;
const t0 = performance.now();
for (const name of new Set([...Object.keys(ref), ...g.names.keys()])) {
  const js = g.names.has(name) ? await g.dbc(name) : null;
  if (js === ref[name]) continue;
  bad++;
  if (js === null || ref[name] === undefined) {
    console.log(`${name}: ${js === null ? "not generated by js" : "not generated by python"}`);
    continue;
  }
  let at = 0;
  while (js[at] === ref[name][at]) at++;
  console.log(`${name}: differs at ${at}\n  js:  ${JSON.stringify(js.slice(at - 40, at + 60))}\n  ref: ${JSON.stringify(ref[name].slice(at - 40, at + 60))}`);
}
const n = Object.keys(ref).length;
console.log(bad ? `${bad} of ${n} differ` : `all ${n} generated DBCs identical (js ${(performance.now() - t0).toFixed(0)} ms)`);
process.exit(bad ? 1 : 0);
