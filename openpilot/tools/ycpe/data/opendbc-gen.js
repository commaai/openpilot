// port of opendbc/dbc/generator/generator.py: DBCs opendbc assembles at build time instead of checking in. Templates
// pull in shared parts with CM_ "IMPORT x" lines; a few Python scripts emit DBCs (or parts) themselves. The ports
// below keep the scripts' text where it lives: literal blocks are read from the script at the same commit, and only
// the loops around them are ported.

const INCLUDE = /CM_ "IMPORT (.*?)";\n/g;

export class Generator {
  // files: paths under generator/ ("honda/acura_ilx_2016_can.dbc"); read(path) gives a file's text or null
  constructor(files, read) {
    this.read = async (f) => {
      const t = await read(f);
      if (t === null) throw new Error(`generator/${f} not found`);
      return t.replace(/\r\n?/g, "\n");  // Python reads text with universal newlines
    };
    this.names = new Map();  // DBC name → [dir, template file]
    this.scripts = {};  // dir → the scripts that run there
    this.outputs = {};  // dir → the scripts' output, once run
    for (const f of files.slice().sort()) {
      const [dir, file, more] = f.split("/");
      if (!file || more) continue;
      if (file.endsWith(".py") && SCRIPTS[f]) {
        (this.scripts[dir] ||= []).push(file);
        for (const out of SCRIPTS[f].outputs) if (!out.startsWith("_")) this.names.set(out.replace(/\.dbc/g, "_generated"), [dir, out]);
      } else if (file.endsWith(".dbc") && !file.startsWith("_")) {
        this.names.set(file.replace(/\.dbc/g, "_generated"), [dir, file]);
      }
    }
  }

  // the files the dir's scripts produce, as generator.py's _collect_script_outputs()
  run(dir) {
    return this.outputs[dir] ||= (async () => {
      const out = {};
      for (const file of this.scripts[dir] || []) {
        const local = (f) => this.read(`${dir}/${f}`);
        Object.assign(out, await SCRIPTS[`${dir}/${file}`].run(local, await local(file)));
      }
      return out;
    })();
  }

  async dbc(name) {
    const [dir, file] = this.names.get(name);
    const extra = await this.run(dir);
    const src = (f) => f in extra ? extra[f] : this.read(`${dir}/${f}`);
    const template = await src(file);
    const parts = ['CM_ "AUTOGENERATED FILE, DO NOT EDIT";\n'];
    for (const [, inc] of template.matchAll(INCLUDE)) parts.push(`\n\nCM_ "Imported file ${inc} starts here";\n`, await src(inc));
    parts.push(`\nCM_ "${file} starts here";\n`, template.replace(INCLUDE, ""));
    return parts.join("");
  }
}

// ---- the script generators

// a script's triple-quoted literals in order, escapes applied: [{f: is an f-string, text}]
function literals(py) {
  return [...py.matchAll(/(f?)"""([\s\S]*?)"""/g)].map(([, f, s]) => ({f: !!f, text: unescape(s)}));
}

const ESC = {"\n": "", "\\": "\\", '"': '"', "'": "'", n: "\n", t: "\t"};
const unescape = (s) => s.replace(/\\([\n\\"'nt])/g, (_, c) => ESC[c]);

// fills an f-string's {expr} fields from vars, keyed by the exact expression text
function fill(lit, vars) {
  return lit.text.replace(/\{([^{}]+)\}/g, (_, e) => {
    if (!(e in vars)) throw new Error(`generator: unported f-string field {${e}}`);
    return vars[e];
  });
}

const hex = (a) => a.toString(16);
const range = (a, b, step = 1) => Array.from({length: Math.ceil((b - a) / step)}, (_, i) => a + i * step);

// Python's repr of a number: floats keep a ".0"
const py = (x, float) => float && Number.isInteger(x) ? `${x}.0` : String(x);
const round10 = (x, float) => float ? Number(x.toFixed(10)) : x;

// tesla/_radar_common.py's two f-strings
async function teslaCommon(read) {
  const [point, val] = literals(await read("_radar_common.py"));
  return {
    point: (base, name) => fill(point, {base_id: base, "base_id+1": base + 1, base_name: name}),
    val: (base) => fill(val, {"base_id+1": base + 1}),
  };
}

const SCRIPTS = {
  "chrysler/_stellantis_common_ram.py": {
    outputs: ["_stellantis_common_ram_dt_generated.dbc", "_stellantis_common_ram_hd_generated.dbc"],
    // Chrysler's common messages at RAM's addresses; the address map is read from the script
    async run(read, script) {
      const src = "_stellantis_common.dbc", text = await read(src), out = {};
      for (const [, name, body] of script.matchAll(/"([^"]+\.dbc)": \{([^}]*)\}/g)) {
        const lookup = new Map([...body.matchAll(/(\d+): (\d+)/g)].map(([, a, b]) => [+a, +b]));
        const parts = [`CM_ "Generated from ${src}"\n\n`];
        for (let line of text.split(/(?<=\n)/)) {
          if (line.startsWith("BO_") || line.startsWith("VAL_")) {
            const sl = line.split(" "), addr = parseInt(sl[1]);
            sl[1] = String(lookup.get(addr) ?? addr);
            line = sl.join(" ");
          }
          parts.push(line);
        }
        out[name] = parts.join("");
      }
      return out;
    },
  },
  "tesla/tesla_radar_bosch.py": {
    outputs: ["tesla_radar_bosch.dbc"],
    async run(read, script) {
      const [head, tail] = literals(script), c = await teslaCommon(read);
      const m = range(0x310, 0x36D + 1, 3), l = range(0x371, 0x37D + 1, 3);
      const parts = [head.text, ...m.map((b, i) => c.point(b, `RadarPoint${i}`)), ...l.map((b, i) => c.point(b, `ProcessedRadarPoint${i + 1}`)), tail.text];
      return {"tesla_radar_bosch.dbc": [...parts, ...[...m, ...l].map(c.val)].join("")};
    },
  },
  "tesla/tesla_radar_continental.py": {
    outputs: ["tesla_radar_continental.dbc"],
    async run(read, script) {
      const [head, tail] = literals(script), c = await teslaCommon(read);
      const points = range(0x410, 0x45E + 1, 2);
      return {"tesla_radar_continental.dbc": [head.text, ...points.map((b, i) => c.point(b, `RadarPoint${i}`)), tail.text, ...points.map(c.val)].join("")};
    },
  },
  "hyundai/hyundai_kia_mando_front_radar.py": {
    outputs: ["hyundai_kia_mando_front_radar.dbc"],
    async run(read, script) {
      const [head, track] = literals(script);
      return {"hyundai_kia_mando_front_radar.dbc": [head.text, ...range(0x500, 0x520).map((a) => fill(track, {a, "a:x": hex(a)}))].join("")};
    },
  },
  "hyundai/hyundai_kia_mando_corner_radar.py": {
    outputs: ["hyundai_kia_mando_corner_radar.dbc"],
    async run(read, script) {
      const [head, meta, points, crc] = literals(script);
      const parts = [head.text, ...[0x100, 0x200].map((a) => fill(meta, {a, "a:x": hex(a)}))];
      // [name, start, length, scale, offset], numbers as [value, is a float]; points are 101 bits, five a message
      const signals = [
        ["DISTANCE", 7, 14, [1 / 64, 1], [0]], ["", 21, 2, [1], [0]], ["", 23, 8, [1 / 512, 1], [-127 / 512, 1]],
        ["REL_VELOCITY", 31, 13, [1 / 32, 1], [-66]], ["", 44, 2, [1], [0]], ["", 46, 2, [1], [0]],
        ["AZIMUTH", 48, 12, [1 / 512, 1], [-2047 / 512, 1]], ["", 60, 2, [1], [0]], ["", 62, 1, [1], [0]], ["", 63, 7, [1], [0]],
        ["", 70, 1, [1], [0]], ["", 71, 6, [1], [0]], ["", 77, 2, [1], [0]], ["", 79, 8, [1 / 512, 1], [-127 / 512, 1]],
        ["", 87, 1, [1], [0]], ["", 88, 2, [1], [0]], ["", 90, 3, [1], [0]], ["", 93, 6, [1], [0]], ["", 99, 8, [1], [0]], ["", 107, 1, [1], [0]],
      ];
      const bits = signals.reduce((n, s) => n + s[2], 0);
      for (const a of [0x101, 0x201]) {
        parts.push(fill(points, {a, "a:x": hex(a)}));
        for (let i = 0; i < 5; i++) {
          signals.forEach(([name, start, length, [scale, sf], [offset, of]], k) => {
            const sig = name ? `POINT_${i + 1}_${name}` : `POINT_${i + 1}_SIGNAL_${k + 1}`;
            const lo = round10(offset, of), hi = round10((2 ** length - 1) * scale + offset, sf || of);
            parts.push(` SG_ ${sig} : ${i * bits + start}|${length}@1+ (${py(scale, sf)},${py(offset, of)}) [${py(lo, of)}|${py(hi, sf || of)}] "" XXX\n`);
          });
        }
      }
      parts.push(...[0x104, 0x204].map((a) => fill(crc, {a, "a:x": hex(a)})));
      return {"hyundai_kia_mando_corner_radar.dbc": parts.join("")};
    },
  },
  "rivian/rivian_mando_front_radar.py": {
    outputs: ["rivian_mando_front_radar.dbc"],
    async run(read, script) {
      const [head, track, val] = literals(script), a = range(0x500, 0x520);
      return {"rivian_mando_front_radar.dbc": [head.text, ...a.map((x) => fill(track, {a: x, "a:x": hex(x)})), ...a.map((x) => fill(val, {a: x}))].join("")};
    },
  },
};
