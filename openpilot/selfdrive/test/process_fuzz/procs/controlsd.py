def template(svc, g=None):
  m = U.shape(svc)
  if svc == 'lateralTorqueParameters':  # torqued's image: latAccelFactor > 0 (ledger)
    m.lateralTorqueParameters.latAccelFactorFiltered = 1.
  elif svc == 'carState':
    m.carState.canValid = True
  return m


def behavior(CP):
  # the controller selection and limit implementations a CarParams picks (controlsd.py:56-63, opendbc interfaces)
  CI = interfaces[CP.carFingerprint]
  over = lambda f: getattr(CI, f) is not getattr(CarInterfaceBase, f)  # noqa: E731
  return (str(CP.steerControlType), CP.lateralTuning.which(), CP.steerAtStandstill, CP.minSteerSpeed > 0.3, CP.openpilotLongitudinalControl,
          CP.pcmCruise, over('get_pid_accel_limits') and CI.__module__, over('torque_from_lateral_accel'), over('get_steer_feedforward_function'),
          CP.brand in ('tesla', 'hyundai'), all(v == 0 for v in CP.longitudinalTuning.kiV))


class Space(S.Space):
  def messages(self, g):
    out = []
    for m in super().messages(g):
      if m.which() in ('selfdriveState', 'carState'):
        b = m.as_builder()
        if m.which() == 'selfdriveState':  # selfdrived's image: enabled/active are functions of state
          b.selfdriveState.enabled = b.selfdriveState.state in ENABLED_STATES
          b.selfdriveState.active = b.selfdriveState.state in ACTIVE_STATES
        else:  # card: cs_send.valid = CS.canValid (card.py:212)
          b.carState.canValid = b.carState.canValid and b.valid
          b.valid = b.carState.canValid
        m = log.Event.from_bytes(b.to_bytes()).__enter__()
      out.append(m)
    return out


def bad(sp):
  # a read float NaN/inf/huge (the theoretical classes), or a torque factor torqued never publishes (ledger)
  def f(m):
    ltp = m.which() == 'lateralTorqueParameters' and m.lateralTorqueParameters
    return sp.bad(m) or bool(ltp and ltp.useParams and not ltp.latAccelFactorFiltered > 0)
  return f


# *** cycle view: the k-th selfdriveState is the k-th carControl/controlsState (lockstep) ***

def cycles(r):
  for c in P.cycles(r, ('carControl', 'controlsState'), 'selfdriveState'):
    yield c, c.out['carControl'].carControl, c.out['controlsState'].controlsState


def held(c, svc):
  return getattr(c.last[svc], svc) if svc in c.last else getattr(S.new_message(svc), svc)


@P.prop('invariant actuators finite')
def actuators_finite(r):
  # actuation is never excused by valid=False (controlsd.py:140-147 guard)
  for c, cc, _ in cycles(r):
    bad = P.nonfinite(cc.actuators.to_dict(), 'actuators')
    assert not bad, f't={c.t:.2f}s {bad}'
  return True


@P.prop('invariant gating')
def gating(r):
  # actuators only act when selfdrived says so, and are inert otherwise (controlsd.py:96-147)
  angle, curv = r.cp.steerControlType == 'angle', r.cp.steerControlType == 'curvature'
  for c, cc, cs in cycles(r):
    ss, CS, t = held(c, 'selfdriveState'), held(c, 'carState'), f't={c.t:.2f}s'
    ev = held(c, 'onroadEvents')
    assert cc.enabled == ss.enabled, f'{t} enabled {cc.enabled} vs selfdriveState {ss.enabled}'
    assert not cc.latActive or (ss.active and not CS.steerFaultTemporary and not CS.steerFaultPermanent), f'{t} latActive with {ss.state} / steer fault'
    assert not cc.longActive or (ss.enabled and r.cp.openpilotLongitudinalControl and not any(e.overrideLongitudinal for e in ev)), \
      f'{t} longActive while not enabled, overridden or not openpilot long'
    a = cc.actuators
    if not cc.longActive:
      assert a.accel == 0 and cs.longControlState == 'off', f'{t} long inactive: accel {a.accel} state {cs.longControlState}'
    if not cc.latActive:
      assert a.torque == 0, f'{t} lat inactive: torque {a.torque}'
      if angle and math.isfinite(CS.steeringAngleDeg):
        assert np.float32(a.steeringAngleDeg) == np.float32(CS.steeringAngleDeg), f'{t} lat inactive: angle {a.steeringAngleDeg} vs {CS.steeringAngleDeg}'
      if curv:
        assert a.curvature == 0, f'{t} lat inactive: curvature {a.curvature}'
  return True


@P.prop('invariant actuator limits')
def limits(r):
  CP = r.cp
  CI, torque_ok = interfaces[CP.carFingerprint], True
  for c, cc, _ in cycles(r):
    CS, a, t, ltp = held(c, 'carState'), cc.actuators, f't={c.t:.2f}s', held(c, 'lateralTorqueParameters')
    # ledger: torqued keeps latAccelFactor > 0; 0 or negative inverts the pid limits
    torque_ok = torque_ok and (CP.lateralTuning.which() != 'torque' or not ltp.useParams or ltp.latAccelFactorFiltered > 0)
    assert not torque_ok or abs(a.torque) <= 1., f'{t} torque {a.torque}'
    assert abs(a.curvature) <= MAX_CURVATURE + 1e-7, f'{t} curvature {a.curvature}'
    if cc.longActive and math.isfinite(CS.vEgo) and math.isfinite(CS.vCruise):
      lo, hi = CI.get_pid_accel_limits(CP, CS.vEgo, CS.vCruise * CV.KPH_TO_MS)
      assert lo - 1e-6 <= a.accel <= hi + 1e-6 or a.accel == 0, f'{t} accel {a.accel} not in [{lo}, {hi}]'
  return True


@P.prop('invariant curvature limits')
def curvature_limits(r):
  # desiredCurvature respects the ISO lateral accel and jerk limits and MAX_CURVATURE (drive_helpers.py:27-41)
  prev = 0.
  for c, _, cs in cycles(r):
    d, v, roll = cs.desiredCurvature, max(held(c, 'carState').vEgo, MIN_SPEED), held(c, 'vehicleParameters').roll
    if not (math.isfinite(d) and math.isfinite(v) and math.isfinite(roll) and math.isfinite(prev)):
      prev = d
      continue
    t, tol = f't={c.t:.2f}s', 1e-5 * (abs(d) + 1e-6)
    assert abs(d) <= MAX_CURVATURE + tol, f'{t} |desiredCurvature| {d}'
    g = roll * ACCELERATION_DUE_TO_GRAVITY
    lo, hi = (-MAX_LATERAL_ACCEL_NO_ROLL + g) / v ** 2, (MAX_LATERAL_ACCEL_NO_ROLL + g) / v ** 2
    at_bound = abs(abs(d) - MAX_CURVATURE) <= tol or abs(d - lo) <= tol + 1e-6 * abs(lo) or abs(d - hi) <= tol + 1e-6 * abs(hi)
    assert at_bound or lo - tol <= d <= hi + tol, f'{t} lateral accel {d * v ** 2 - g:.3f} beyond {MAX_LATERAL_ACCEL_NO_ROLL}'
    assert at_bound or abs(d - prev) <= MAX_LATERAL_JERK / v ** 2 * DT_CTRL * (1 + 1e-5) + tol, f'{t} curvature step {d - prev} at v {v}'
    prev = d
  return True


@P.prop('invariant hud and cruise')
def hud_cruise(r):
  for c, cc, cs in cycles(r):
    ss, CS, lp, dm = held(c, 'selfdriveState'), held(c, 'carState'), held(c, 'longitudinalPlan'), held(c, 'driverMonitoringState')
    t, h, cr = f't={c.t:.2f}s', cc.hudControl, cc.cruiseControl
    assert h.leadDistanceBars in (1, 2, 3), f'{t} leadDistanceBars {h.leadDistanceBars}'
    assert h.speedVisible == h.lanesVisible == cc.enabled and h.leadVisible == lp.hasLead, f'{t} hud {h}'
    assert cs.forceDecel == (dm.noResponseForceDecel or ss.state == State.softDisabling) == cc.driverMonitoringEscalation, f'{t} forceDecel'
    assert cr.override == (cc.enabled and not cc.longActive and r.cp.openpilotLongitudinalControl), f'{t} override {cr}'
    assert not cr.resume or (cc.enabled and CS.cruiseState.standstill and not lp.shouldStop), f'{t} resume {cr}'
  return True


@P.prop('invariant not cancel and resume')
def cancel_resume(r):
  for c, cc, _ in cycles(r):
    cr = cc.cruiseControl
    assert not (cr.cancel and cr.resume), f't={c.t:.2f}s cancel and resume together: pcmCruise {r.cp.pcmCruise}, {held(c, "carState").cruiseState}'
  return True


@P.prop('invariant longControlState consistent')
def long_state_consistent(r):
  for c, cc, cs in cycles(r):
    assert cc.actuators.longControlState == cs.longControlState, \
      f't={c.t:.2f}s carControl.actuators {cc.actuators.longControlState} vs controlsState {cs.longControlState}'
  return True


@P.prop('valid_from_inputs carControl (carState)')
def valid_cs(r):
  for c, _, _ in cycles(r):
    assert not c.out['carControl'].valid or ('carState' in c.last and c.last['carState'].valid), f't={c.t:.2f}s valid with carState invalid'
  return True


def lat_steady(r):
  # selfdrived's state, steer faults and carState.standstill: with them held, latActive only depends on vEgo vs the standstill threshold
  return [(held(c, 'selfdriveState').active, held(c, 'carState').steerFaultTemporary, held(c, 'carState').steerFaultPermanent,
           held(c, 'carState').standstill) for c, _, _ in cycles(r)]


def long_pid(r):
  t, _ = P.series(r.outs, 'carControl.actuators.accel')
  st = [s is not None and str(s) == 'pid' for s in P.held(r.outs, 'controlsState.longControlState', t)]
  return P.held_for(t, np.array(st, dtype=bool), 0.5)


